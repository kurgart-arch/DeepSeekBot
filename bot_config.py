def _get_env_var(name: str, required: bool = True, default: str = None) -> str:
    value = os.getenv(name)
    if not value:
        if required:
            raise ValueError(f"Environment variable {name} is required!")
        logger.info(f"{name} не задана, использую значение по умолчанию")
        return default
    logger.info(f"Loaded {name}")
    return value


class BotConfig:
    def __init__(self):
        self.telegram_bot_token = _get_env_var('TELEGRAM_BOT_TOKEN')
        self.openrouter_api_key = _get_env_var('OPENROUTER_API_KEY')

        self.model = _get_env_var('DEEPSEEK_MODEL', required=False,
                                  default='deepseek-chat')
        self.max_tokens = int(_get_env_var('MAX_TOKENS', required=False,
                                           default='600'))
        self.temperature = float(_get_env_var('TEMPERATURE', required=False,
                                              default='0.8'))
        self.request_timeout = float(_get_env_var('REQUEST_TIMEOUT',
                                                  required=False, default='60'))

        self.max_history_messages = int(_get_env_var('MAX_HISTORY_MESSAGES',
                                                     required=False, default='12'))
        self.memory_messages = int(_get_env_var('MEMORY_MESSAGES',
                                                required=False, default='50'))
        self.memory_file = _get_env_var('MEMORY_FILE', required=False,
                                        default='chat_memory.json')
        self.user_data_file = _get_env_var('USER_DATA_FILE', required=False,
                                           default='user_data.json')

        self.system_prompt = SYSTEM_PROMPT
